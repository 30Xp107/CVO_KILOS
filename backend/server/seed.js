async function seedAdmin() {
  const email = (process.env.ADMIN_EMAIL || "admin@kilos.local").trim().toLowerCase();
  const password = process.env.ADMIN_PASSWORD || "Admin@Kilos2026";
  const name = process.env.ADMIN_NAME || "KILOS Administrator";

  const existing = await Admin.findOne({ email });
  if (existing) {
    console.log(`Admin already exists: ${email}`);
    return;
  }

  await Admin.create({
    name,
    email,
    passwordHash: await bcrypt.hash(password, 10),
    role: "admin",
  });
  console.log(`Created admin: ${email}`);
}

async function seed(options = {}) {
  await connectDB();

  if (options.clearDemo) {
    const removed = await Submission.deleteMany({ referenceNo: /^KILOS-DEMO-/ });
    console.log(`Removed ${removed.deletedCount} demo submission(s).`);
    return;
  }

  await seedAdmin();

  if (options.force) {
    const removed = await Submission.deleteMany({ referenceNo: /^KILOS-DEMO-/ });
    console.log(`Removed ${removed.deletedCount} existing demo submission(s).`);
  }

  const existingCount = await Submission.countDocuments({ referenceNo: /^KILOS-DEMO-/ });
  if (existingCount > 0) {
    console.log(
      `Found ${existingCount} demo submission(s). Run "npm run seed -- --force" to replace them.`
    );
    return;
  }

  let created = 0;
  for (let index = 0; index < samples.length; index += 1) {
    const sample = samples[index];
    const parsed = submissionSchema.parse({
      ...sample,
      website: "",
    });

    await Submission.create({
      ...parsed,
      referenceNo: `${demoPrefix}${String(index + 1).padStart(2, "0")}`,
      status: sample.status || "new",
      submittedAt: sample.submittedAt || new Date(),
    });
    created += 1;
  }

  console.log(`Created ${created} demo submission(s).`);
  const total = await Submission.countDocuments();
  console.log(`Total submissions in database: ${total}`);
}

const force = process.argv.includes("--force");
const clearDemo = process.argv.includes("--clear-demo");

seed({ force, clearDemo })
  .then(async () => {
    await mongoose.disconnect();
    process.exit(0);
  })
  .catch(async (error) => {
    console.error("Seed failed:", error.message);
    if (error.issues) {
      console.error(JSON.stringify(error.issues, null, 2));
    }
    await mongoose.disconnect().catch(() => {});
    process.exit(1);
  });
