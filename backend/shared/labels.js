export function label(map, value, fallback = "") {
  if (!value) return "";
  return LABELS[map]?.[value] || fallback || value;
}

export function labels(map, values = []) {
  return (values || []).map((value) => label(map, value)).filter(Boolean);
}

export function joinLabels(map, values = [], separator = ", ") {
  return labels(map, values).join(separator);
}

export function yesNo(value) {
  if (value === "yes") return "Yes";
  if (value === "no") return "No";
  return value || "";
}
